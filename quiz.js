/**
 * picks: one answer index (0–3) per answered question, in order.
 * Main +2, second +1; highest total wins. Tie: of the tied fairies, the one
 * picked as main most recently wins.
 */
export function result(picks) {
  const score = {};
  const lastMain = {};
  picks.forEach((pick, q) => {
    const [main, second] = QUESTIONS[q].answers[pick];
    score[main] = (score[main] ?? 0) + 2;
    score[second] = (score[second] ?? 0) + 1;
    lastMain[main] = q;
  });
  const top = Math.max(...Object.values(score));
  const tied = Object.keys(score).filter((f) => score[f] === top);
  return tied.reduce((a, b) => ((lastMain[b] ?? -1) > (lastMain[a] ?? -1) ? b : a));
}
